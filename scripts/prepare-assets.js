/*
 * Runs before start/build/test.
 *
 * 1. Mirrors the web-ready (WebP/AVIF/SVG) files from the owner-supplied
 *    avatar/ folder into public/avatar/ so the app can serve them. The PNG
 *    originals stay in avatar/ and are not published. avatar/ is only ever
 *    read, never written.
 * 2. Writes src/generated/assetManifest.js listing every file that exists
 *    under public/assets/ and public/avatar/, so components can render a
 *    designed fallback instead of requesting (and 404ing on) missing art.
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const avatarSource = path.join(root, "avatar");
const avatarTarget = path.join(root, "public", "avatar");
const publicDir = path.join(root, "public");
const manifestFile = path.join(root, "src", "generated", "assetManifest.js");

const WEB_IMAGE_EXT = /\.(webp|svg|avif)$/i;
const IGNORED = new Set([".gitkeep", ".DS_Store", "Thumbs.db"]);

function listFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return listFiles(full);
    return IGNORED.has(entry.name) ? [] : [full];
  });
}

function syncAvatars() {
  fs.mkdirSync(avatarTarget, { recursive: true });
  const sources = fs.existsSync(avatarSource)
    ? fs.readdirSync(avatarSource).filter((name) => WEB_IMAGE_EXT.test(name))
    : [];

  for (const name of fs.readdirSync(avatarTarget)) {
    if (!sources.includes(name)) fs.rmSync(path.join(avatarTarget, name), { force: true });
  }
  for (const name of sources) {
    fs.copyFileSync(path.join(avatarSource, name), path.join(avatarTarget, name));
  }
  return sources;
}

function writeManifest() {
  const files = [
    ...listFiles(path.join(publicDir, "assets")),
    ...listFiles(avatarTarget),
  ]
    .map((file) => path.relative(publicDir, file).split(path.sep).join("/"))
    .sort();

  fs.mkdirSync(path.dirname(manifestFile), { recursive: true });
  fs.writeFileSync(
    manifestFile,
    "// Generated by scripts/prepare-assets.js. Do not edit.\n" +
      `const files = ${JSON.stringify(files, null, 2)};\n` +
      "export default files;\n"
  );
  return files;
}

const avatars = syncAvatars();
const files = writeManifest();
console.log(
  `[prepare-assets] avatars: ${avatars.length ? avatars.join(", ") : "none (fallback crest will render)"}; ` +
    `manifest: ${files.length} file(s)`
);
