import { act, fireEvent, render, screen } from "@testing-library/react";
import CodeReviewRater from "../pages/tools/ai/CodeReviewRater";
import JiraTicketScorer from "../pages/tools/ai/JiraTicketScorer";
import PromptDebugger from "../pages/tools/ai/PromptDebugger";
import { AiRequestError, describeError, requestAnalysis } from "../pages/tools/ai/aiClient";
import { AI_RESULTS } from "../testFixtures/aiResults";

const API = "https://lab-ai.example.workers.dev";
const KEYLIKE = "sk-proj-SHOULD-NEVER-APPEAR";

function jsonResponse(status, body) {
  return { ok: status >= 200 && status < 300, status, json: async () => body };
}

function deferred() {
  let resolve;
  const promise = new Promise((r) => {
    resolve = r;
  });
  return { promise, resolve };
}

const originalUrl = process.env.REACT_APP_AI_API_URL;
beforeEach(() => {
  process.env.REACT_APP_AI_API_URL = `${API}/`;
  global.fetch = jest.fn();
});
afterEach(() => {
  process.env.REACT_APP_AI_API_URL = originalUrl;
  delete global.fetch;
});

const promptBox = () => screen.getByLabelText("Prompt");
const debugButton = () => screen.getByRole("button", { name: /Debug prompt|Analysing/ });
const type = (value) => fireEvent.change(promptBox(), { target: { value } });

describe("AI instruments: disclosure and configuration", () => {
  test("say plainly, before anything is sent, that text goes to the AI service", () => {
    render(<PromptDebugger />);
    const disclosure = screen.getByText(/the text you entered is sent to this site's AI service and on to OpenAI/);
    expect(disclosure).toBeVisible();
    expect(disclosure).toHaveTextContent("AI-powered");
    expect(promptBox()).toHaveAccessibleDescription(expect.stringContaining("sent to this site's AI service"));
    expect(screen.getByText(/AI-generated by an OpenAI model. It can be wrong/)).toBeInTheDocument();
    expect(global.fetch).not.toHaveBeenCalled();
  });

  test("typing never sends anything", () => {
    render(<PromptDebugger />);
    type("hello");
    expect(global.fetch).not.toHaveBeenCalled();
  });

  test("without a configured endpoint the instrument explains it cannot run and sends nothing", () => {
    process.env.REACT_APP_AI_API_URL = "";
    render(<PromptDebugger />);
    expect(screen.getByText(/not connected to its AI service/)).toBeInTheDocument();
    type("A prompt");
    fireEvent.click(debugButton());
    expect(screen.getByRole("alert")).toHaveTextContent("AI service not connected");
    expect(global.fetch).not.toHaveBeenCalled();
  });
});

describe("AI instruments: input checks", () => {
  test("empty input shows a prompt instead of sending", () => {
    render(<PromptDebugger />);
    type("   ");
    fireEvent.click(debugButton());
    expect(screen.getByText("Enter some text first.", { selector: ".pv-output__warning" })).toBeInTheDocument();
    expect(global.fetch).not.toHaveBeenCalled();
  });

  test("the character limit is shown, enforced on the field, and checked before sending", () => {
    render(<PromptDebugger />);
    expect(promptBox()).toHaveAttribute("maxLength", "4000");
    expect(screen.getByText("0 of 4,000 characters")).toBeInTheDocument();
    type("a".repeat(4000));
    expect(screen.getByText(/Limit reached/)).toBeInTheDocument();
    type("a".repeat(4001));
    expect(screen.getByText(/1 over the limit/)).toBeInTheDocument();
    fireEvent.click(debugButton());
    expect(screen.getByRole("alert")).toHaveTextContent("The text is too long");
    expect(global.fetch).not.toHaveBeenCalled();
  });

  test("each instrument has its own limit", () => {
    render(<CodeReviewRater />);
    expect(screen.getByLabelText("Code")).toHaveAttribute("maxLength", "8000");
    render(<JiraTicketScorer />);
    expect(screen.getByLabelText("Ticket")).toHaveAttribute("maxLength", "6000");
  });
});

describe("AI instruments: requests", () => {
  test("posts only the text to the Laboratory endpoint, never to OpenAI and never with a key", async () => {
    global.fetch.mockResolvedValue(jsonResponse(200, { ok: true, result: AI_RESULTS["prompt-debugger"] }));
    render(<PromptDebugger />);
    type("Summarise this");
    fireEvent.click(debugButton());
    await screen.findByText("Revised prompt");

    expect(global.fetch).toHaveBeenCalledTimes(1);
    const [url, init] = global.fetch.mock.calls[0];
    expect(url).toBe(`${API}/api/prompt-debugger`);
    expect(url).not.toMatch(/openai\.com/);
    expect(init).toMatchObject({ method: "POST", credentials: "omit" });
    expect(init.headers).toEqual({ "Content-Type": "application/json" });
    expect(JSON.parse(init.body)).toEqual({ text: "Summarise this" });
  });

  test("shows a loading state and ignores repeat submissions while a request runs", async () => {
    const pending = deferred();
    global.fetch.mockReturnValue(pending.promise);
    render(<PromptDebugger />);
    type("Summarise this");
    fireEvent.click(debugButton());

    expect(debugButton()).toBeDisabled();
    expect(debugButton()).toHaveTextContent("Analysing...");
    expect(screen.getByText(/Consulting the AI/)).toBeInTheDocument();
    expect(screen.getByRole("region", { name: "Prompt analysis" })).toHaveAttribute("aria-busy", "true");
    expect(promptBox()).toHaveAttribute("readOnly");
    fireEvent.click(debugButton());
    fireEvent.click(debugButton());
    expect(global.fetch).toHaveBeenCalledTimes(1);

    await act(async () => pending.resolve(jsonResponse(200, { ok: true, result: AI_RESULTS["prompt-debugger"] })));
    expect(debugButton()).not.toBeDisabled();
    expect(screen.getByText("Prompt analysis ready.")).toHaveAttribute("role", "status");
  });

  test("Prompt Debugger renders clarity, problems, recommendations and a revised prompt", async () => {
    global.fetch.mockResolvedValue(jsonResponse(200, { ok: true, result: AI_RESULTS["prompt-debugger"] }));
    render(<PromptDebugger />);
    type("Write something");
    fireEvent.click(debugButton());
    const result = await screen.findByTestId("pv-pd-result");
    expect(result).toHaveTextContent("Clarity");
    expect(result).toHaveTextContent("Needs work");
    expect(result).toHaveTextContent("Problems");
    expect(result).toHaveTextContent("Recommendations");
    expect(screen.getByLabelText("Revised prompt")).toHaveValue(AI_RESULTS["prompt-debugger"].revisedPrompt);
    expect(screen.getByRole("button", { name: "Copy revised prompt" })).toBeEnabled();
  });

  test("Code Review Rater renders every review section", async () => {
    global.fetch.mockResolvedValue(jsonResponse(200, { ok: true, result: AI_RESULTS["code-review"] }));
    render(<CodeReviewRater />);
    fireEvent.change(screen.getByLabelText("Code"), { target: { value: "const a = 1;" } });
    fireEvent.click(screen.getByRole("button", { name: /Review code/ }));
    const result = await screen.findByTestId("pv-cr-result");
    for (const heading of ["Overall", "Readability", "Maintainability", "Potential bugs", "Security concerns", "Recommendations"]) {
      expect(result).toHaveTextContent(heading);
    }
    expect(global.fetch.mock.calls[0][0]).toBe(`${API}/api/code-review`);
  });

  test("JIRA Ticket Scorer renders quality, missing information, criteria, context and an improved ticket", async () => {
    global.fetch.mockResolvedValue(jsonResponse(200, { ok: true, result: AI_RESULTS["jira-ticket"] }));
    render(<JiraTicketScorer />);
    fireEvent.change(screen.getByLabelText("Ticket"), { target: { value: "Login broken" } });
    fireEvent.click(screen.getByRole("button", { name: /Score ticket/ }));
    const result = await screen.findByTestId("pv-jt-result");
    for (const heading of ["Quality", "Missing information", "Acceptance criteria", "Reproducibility and context", "Bug"]) {
      expect(result).toHaveTextContent(heading);
    }
    expect(screen.getByLabelText("Improved ticket")).toHaveValue(AI_RESULTS["jira-ticket"].improvedTicket);
    expect(global.fetch.mock.calls[0][0]).toBe(`${API}/api/jira-ticket`);
  });

  test("a request can be cancelled", async () => {
    global.fetch.mockImplementation((url, init) => new Promise((resolve, reject) => init.signal.addEventListener("abort", () => reject(new DOMException("Aborted", "AbortError")))));
    render(<PromptDebugger />);
    type("Summarise this");
    fireEvent.click(debugButton());
    fireEvent.click(screen.getByRole("button", { name: "Cancel request" }));
    await screen.findByText("Request cancelled. Nothing more will be received.");
    expect(debugButton()).toBeEnabled();
    expect(screen.queryByRole("alert")).toBeNull();
  });
});

describe("AI instruments: errors", () => {
  test.each([
    [429, "rate_limited", "Too many requests"],
    [503, "not_configured", "AI service not connected"],
    [504, "timeout", "The AI service took too long"],
    [413, "input_too_long", "The text is too long"],
    [422, "refused", "The AI declined this text"],
    [502, "upstream_auth", "The AI service is unavailable"],
    [500, "something_new", "The AI service is unavailable"],
  ])("HTTP %i %s shows a friendly message with the code beneath", async (status, code, title) => {
    global.fetch.mockResolvedValue(jsonResponse(status, { ok: false, error: code, message: `Server detail ${KEYLIKE}` }));
    render(<PromptDebugger />);
    type("Summarise this");
    fireEvent.click(debugButton());
    const alert = await screen.findByRole("alert");
    expect(alert).toHaveTextContent(title);
    expect(alert).toHaveTextContent(`Error code: ${code} (HTTP ${status})`);
    expect(document.body.textContent).not.toContain(KEYLIKE);
    expect(debugButton()).toBeEnabled();
  });

  test("a network failure shows a connection message without the raw error", async () => {
    global.fetch.mockRejectedValue(new TypeError(`Failed to fetch ${KEYLIKE}`));
    render(<PromptDebugger />);
    type("Summarise this");
    fireEvent.click(debugButton());
    expect(await screen.findByRole("alert")).toHaveTextContent("Could not reach the AI service");
    expect(document.body.textContent).not.toContain(KEYLIKE);
  });

  test("a success response with an unexpected body is treated as unreadable", async () => {
    global.fetch.mockResolvedValue(jsonResponse(200, { ok: true }));
    render(<PromptDebugger />);
    type("Summarise this");
    fireEvent.click(debugButton());
    expect(await screen.findByRole("alert")).toHaveTextContent("The answer could not be read");
  });

  test("Try again returns focus to the input", async () => {
    global.fetch.mockRejectedValue(new TypeError("Failed to fetch"));
    render(<PromptDebugger />);
    type("Summarise this");
    fireEvent.click(debugButton());
    fireEvent.click(await screen.findByRole("button", { name: "Try again" }));
    expect(promptBox()).toHaveFocus();
  });
});

describe("AI client", () => {
  test("times out a request that never answers", async () => {
    global.fetch.mockImplementation((url, init) => new Promise((resolve, reject) => init.signal.addEventListener("abort", () => reject(new DOMException("Aborted", "AbortError")))));
    await expect(requestAnalysis("prompt-debugger", "x", { timeoutMs: 20 })).rejects.toMatchObject({ code: "timeout" });
  });

  test("an unconfigured client refuses without calling fetch", async () => {
    process.env.REACT_APP_AI_API_URL = "  ";
    await expect(requestAnalysis("prompt-debugger", "x")).rejects.toMatchObject({ code: "not_configured" });
    expect(global.fetch).not.toHaveBeenCalled();
  });

  test("an unparseable error body still yields a status-based error", async () => {
    global.fetch.mockResolvedValue({ ok: false, status: 502, json: async () => { throw new SyntaxError("x"); } });
    await expect(requestAnalysis("code-review", "x")).rejects.toMatchObject({ code: "unavailable", status: 502 });
  });

  test("error descriptions never echo arbitrary codes", () => {
    expect(describeError(new AiRequestError(`weird ${KEYLIKE}`)).technical).toBe("Error code: unknown");
    expect(describeError(new Error(KEYLIKE))).toMatchObject({ code: "network", title: "Could not reach the AI service" });
  });

  test("the bundled client source contains no OpenAI address or key variable", () => {
    const source = require("fs").readFileSync(require("path").join(__dirname, "../pages/tools/ai/aiClient.js"), "utf8");
    expect(source).not.toMatch(/api\.openai\.com|OPENAI_API_KEY|REACT_APP_OPENAI|Authorization/);
  });
});
